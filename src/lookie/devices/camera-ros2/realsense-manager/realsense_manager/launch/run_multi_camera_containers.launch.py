"""Launch each configured RealSense camera in an independent container."""

import importlib.util
import os

import yaml
from ament_index_python.packages import get_package_share_directory
from launch import LaunchDescription
from launch.actions import (
    DeclareLaunchArgument,
    IncludeLaunchDescription,
    LogInfo,
    OpaqueFunction,
)
from launch.launch_description_sources import PythonLaunchDescriptionSource
from launch.substitutions import LaunchConfiguration
from realsense_manager.package_info import installed_package_version


def load_config(path):
    with open(path, 'r', encoding='utf-8') as stream:
        config = yaml.safe_load(stream) or {}
    if config.get('schema_version', 1) != 1:
        raise RuntimeError('Unsupported camera configuration schema_version')
    cameras = config.get('cameras', {})
    if not isinstance(cameras, dict):
        raise RuntimeError('cameras must be a YAML mapping')
    camera_name_owners = {}
    for alias, camera in cameras.items():
        parameters = camera.get('parameters', {})
        camera_name = parameters.get('camera_name', f'camera_{alias}')
        owner = camera_name_owners.get(camera_name)
        if owner is not None:
            raise RuntimeError(
                f'camera_name {camera_name} is used by both {owner} and {alias}')
        camera_name_owners[camera_name] = alias
    return cameras


def load_container_launch(path):
    spec = importlib.util.spec_from_file_location(
        'realsense_manager_single_container_launch', path)
    if spec is None or spec.loader is None:
        raise RuntimeError(f'Cannot load rs_container_launch.py from {path}')
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def launch_argument_value(value):
    if isinstance(value, bool):
        return 'true' if value else 'false'
    if value is None:
        return ''
    return str(value)


def launch_setup(context):
    config_path = os.path.expanduser(
        LaunchConfiguration('config_file').perform(context))
    manager_share = get_package_share_directory('realsense_manager')
    container_launch_path = os.path.join(
        manager_share, 'launch', 'rs_container_launch.py')
    container_launch = load_container_launch(container_launch_path)
    valid_parameter_names = {
        parameter['name']
        for parameter in container_launch.configurable_parameters
    }
    manager_version = installed_package_version('realsense_manager')
    actions = [LogInfo(
        msg=(
            f'RealSense Manager v{manager_version}: '
            f'loading managed camera containers from {config_path}'))]
    for alias, camera in load_config(config_path).items():
        if not camera.get('enabled', True):
            actions.append(LogInfo(msg=f'Skipping disabled camera alias: {alias}'))
            continue
        parameters = dict(camera.get('parameters', {}))
        serial_number = str(parameters.get('serial_no') or '').strip()
        if not serial_number:
            actions.append(LogInfo(msg=f'Skipping unbound camera alias: {alias}'))
            continue

        camera_name = str(parameters.get('camera_name') or f'camera_{alias}')
        camera_namespace = str(parameters.get('camera_namespace') or '')
        unknown_parameters = sorted(set(parameters) - valid_parameter_names)
        if unknown_parameters:
            raise RuntimeError(
                f'Alias {alias} contains parameters not declared by '
                f'rs_container_launch.py: '
                f'{", ".join(unknown_parameters)}')
        launch_arguments = {
            name: launch_argument_value(value)
            for name, value in parameters.items()
        }
        launch_arguments['serial_no'] = f'_{serial_number}'
        launch_arguments['config_file'] = "''"
        launch_arguments['log_level'] = LaunchConfiguration('log_level')
        launch_arguments['container_name'] = f'{camera_name}_container'
        actions.extend([
            LogInfo(msg=(
                f'Starting {alias} as {camera_namespace}/{camera_name} '
                f'in {camera_name}_container '
                f'(serial={serial_number})')),
            IncludeLaunchDescription(
                PythonLaunchDescriptionSource(container_launch_path),
                launch_arguments=launch_arguments.items(),
            ),
        ])
    return actions


def generate_launch_description():
    return LaunchDescription([
        DeclareLaunchArgument(
            'config_file',
            default_value=os.path.expanduser(
                '~/.config/realsense_manager/cameras.yaml'),
            description='Camera configuration generated by realsense_manager'),
        DeclareLaunchArgument('log_level', default_value='info'),
        OpaqueFunction(function=launch_setup),
    ])
